"""
Tests for HSPICEWriter.

Validates conversion from IR to HSPICE format.

Compliance: CONSTRAINTS.md
"""

import pytest
from pathlib import Path

from src.writers.hspice_writer import HSPICEWriter
from src.ir.model_ir import (
    ModelIR,
    DeviceType,
    Corner,
    Temperature,
    Condition,
)


class TestHSPICEWriter:
    """Test suite for HSPICEWriter."""

    def test_format_name(self, tmp_path: Path) -> None:
        """Test format name returns 'hspice'."""
        writer = HSPICEWriter(tmp_path / "test.sp")
        assert writer.get_format_name() == "hspice"

    def test_write_simple_model(self, tmp_path: Path) -> None:
        """Test writing a simple model without variations."""
        output_file = tmp_path / "test.sp"
        writer = HSPICEWriter(output_file)

        # Create simple model
        model = ModelIR(
            name="nch",
            model_type="bsim4",
            device_type=DeviceType.NMOS,
        )
        model.base_parameters = {"vth0": 0.4, "tox": 2.5e-9}

        writer.write_from_ir([model])

        # Verify file created
        assert output_file.exists()

        # Read content
        content = output_file.read_text()

        # Verify header
        assert "* Generated by SPICE Translator" in content

        # Verify model
        assert ".model nch nmos" in content
        assert "vth0=0.4" in content
        assert "tox=2.5" in content  # Check for value, format can vary

    def test_write_model_with_corners(self, tmp_path: Path) -> None:
        """Test writing model with corner variations."""
        output_file = tmp_path / "corners.sp"
        writer = HSPICEWriter(output_file)

        # Create model with corners
        model = ModelIR(
            name="nch",
            model_type="bsim4",
            device_type=DeviceType.NMOS,
        )
        model.base_parameters = {"version": "4.7"}

        # Add TT corner
        tt_cond = Condition(corner=Corner.TT, temperature=Temperature.NOMINAL)
        model.add_variation(tt_cond, {"vth0": 0.4, "tox": 2.5e-9})

        # Add FF corner
        ff_cond = Condition(corner=Corner.FF, temperature=Temperature.NOMINAL)
        model.add_variation(ff_cond, {"vth0": 0.35, "tox": 2.4e-9})

        writer.write_from_ir([model])

        # Read content
        content = output_file.read_text()

        # Verify TT section
        assert ".lib tt" in content
        assert "vth0=0.4" in content

        # Verify FF section
        assert ".lib ff" in content
        assert "vth0=0.35" in content

        # Verify .endl markers
        assert content.count(".endl") >= 2

