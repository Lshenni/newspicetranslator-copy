"""
Unit tests for base writer.

Tests the abstract base writer functionality.

Compliance: CONSTRAINTS.md - pytest only
"""

import pytest
from pathlib import Path
from src.writers.base_writer import BaseWriter
from src.ir.model_ir import ModelIR, DeviceType


class MockWriter(BaseWriter):
    """Mock writer for testing base functionality."""
    
    def get_format_name(self) -> str:
        return "mock"
    
    def write_from_ir(self, models):
        """Simple implementation for testing."""
        content = f"* Mock format output\n"
        content += f"* Models: {len(models)}\n"
        for model in models:
            content += f".model {model.name} {model.model_type}\n"
        self._write_content(content)


class TestBaseWriter:
    """Test BaseWriter functionality."""
    
    def test_writer_initialization(self, tmp_path):
        """Test writer initialization."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        assert writer.output_path == output_file
    
    def test_get_format_name(self, tmp_path):
        """Test format name retrieval."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        assert writer.get_format_name() == "mock"
    
    def test_write_content(self, tmp_path):
        """Test writing content to file."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        test_content = "Test content\nLine 2"
        writer._write_content(test_content)
        
        assert output_file.exists()
        assert output_file.read_text() == test_content
    
    def test_write_content_creates_directories(self, tmp_path):
        """Test that write creates parent directories."""
        output_file = tmp_path / "subdir" / "nested" / "output.txt"
        writer = MockWriter(output_file)
        
        writer._write_content("content")
        
        assert output_file.exists()
        assert output_file.read_text() == "content"
    
    def test_generate_header(self, tmp_path):
        """Test header generation."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        header = writer._generate_header("*")
        
        assert "Generated by SPICE Translator" in header
        assert "Target Format: mock" in header
        assert "Generated:" in header
    
    def test_generate_header_custom_comment(self, tmp_path):
        """Test header with custom comment character."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        header = writer._generate_header("//")
        
        assert header.startswith("//")
    
    def test_validate_models_valid(self, tmp_path):
        """Test model validation with valid models."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        models = [
            ModelIR(name="nch", model_type="bsim4", device_type=DeviceType.NMOS),
            ModelIR(name="pch", model_type="bsim4", device_type=DeviceType.PMOS),
        ]
        
        assert writer.validate_models(models) is True
    
    def test_validate_models_empty(self, tmp_path):
        """Test model validation with empty list."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        assert writer.validate_models([]) is False
    
    def test_validate_models_no_name(self, tmp_path):
        """Test model validation with missing name."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        models = [
            ModelIR(name="", model_type="bsim4", device_type=DeviceType.NMOS)
        ]
        
        assert writer.validate_models(models) is False
    
    def test_validate_models_no_type(self, tmp_path):
        """Test model validation with missing type."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        models = [
            ModelIR(name="nch", model_type="", device_type=DeviceType.NMOS)
        ]
        
        assert writer.validate_models(models) is False
    
    def test_write_from_ir(self, tmp_path):
        """Test complete write_from_ir workflow."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        models = [
            ModelIR(name="nch", model_type="bsim4", device_type=DeviceType.NMOS),
            ModelIR(name="pch", model_type="bsim4", device_type=DeviceType.PMOS),
        ]
        
        writer.write_from_ir(models)
        
        assert output_file.exists()
        content = output_file.read_text()
        assert "Mock format output" in content
        assert "Models: 2" in content
        assert ".model nch bsim4" in content
        assert ".model pch bsim4" in content
    
    def test_writer_repr(self, tmp_path):
        """Test writer string representation."""
        output_file = tmp_path / "output.txt"
        writer = MockWriter(output_file)
        
        repr_str = repr(writer)
        assert "MockWriter" in repr_str
        assert "output.txt" in repr_str

    def test_write_content_io_error(self, tmp_path):
        """Test write content handles IO errors."""
        # Try to write to invalid path (read-only or non-existent parent)
        writer = MockWriter(Path("/invalid/path/that/cannot/exist/file.txt"))
        
        with pytest.raises(IOError, match="Write failed"):
            writer._write_content("test content")
