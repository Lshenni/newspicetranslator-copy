    def test_corner_grouping(self, tmp_path: Path) -> None:
        """Test that models are grouped by corner correctly."""
        output_file = tmp_path / "grouped.scs"
        writer = SpectreWriter(output_file)

        # Create two models with same corner
        model1 = ModelIR(
            name="nch", model_type="bsim4", device_type=DeviceType.NMOS
        )
        model2 = ModelIR(
            name="pch", model_type="bsim4", device_type=DeviceType.PMOS
        )

        tt_cond = Condition(corner=Corner.TT, temperature=Temperature.NOMINAL)
        model1.add_variation(tt_cond, {"vth0": 0.4})
        model2.add_variation(tt_cond, {"vth0": -0.4})

        writer.write_from_ir([model1, model2])

        content = output_file.read_text()

        # Count section tt occurrences
        tt_sections = content.count("section tt {")
        assert tt_sections == 1  # Should have only one TT section

        # Both models should be in TT section
        tt_start = content.index("section tt {")
        # Find next section or end of file
        next_section = content.find("\nsection ", tt_start + 1)
        if next_section == -1:
            tt_content = content[tt_start:]
        else:
            tt_content = content[tt_start:next_section]

        assert "nch" in tt_content
        assert "pch" in tt_content

    def test_all_corners(self, tmp_path: Path) -> None:
        """Test writing all corner variations."""
        output_file = tmp_path / "all_corners.scs"
        writer = SpectreWriter(output_file)

        model = ModelIR(
            name="nch",
            model_type="bsim4",
            device_type=DeviceType.NMOS,
        )

        # Add all corners
        for corner in [Corner.TT, Corner.FF, Corner.SS, Corner.FS, Corner.SF]:
            cond = Condition(corner=corner, temperature=Temperature.NOMINAL)
            model.add_variation(cond, {"vth0": 0.4})

        writer.write_from_ir([model])

        content = output_file.read_text()

        # Verify all corner sections
        assert "section tt {" in content
        assert "section ff {" in content
        assert "section ss {" in content
        assert "section fs {" in content
        assert "section sf {" in content

