"""
Tests for SpectreWriter.

Validates conversion from IR to Spectre format.

Compliance: CONSTRAINTS.md
"""

import pytest
from pathlib import Path
import tempfile

from src.writers.spectre_writer import SpectreWriter
from src.ir.model_ir import (
    ModelIR,
    DeviceType,
    Corner,
    Temperature,  # Note: Temperature.NOMINAL = 25°C
    Condition,
)

# Temperature.NOMINAL = 25°C (not T25)


class TestSpectreWriter:
    """Test suite for SpectreWriter."""

    def test_format_name(self, tmp_path: Path) -> None:
        """Test format name returns 'spectre'."""
        writer = SpectreWriter(tmp_path / "test.scs")
        assert writer.get_format_name() == "spectre"

    def test_write_simple_model(self, tmp_path: Path) -> None:
        """Test writing a simple model without variations."""
        output_file = tmp_path / "test.scs"
        writer = SpectreWriter(output_file)

        # Create simple model
        model = ModelIR(
            name="nch",
            model_type="bsim4",
            device_type=DeviceType.NMOS,
        )
        model.base_parameters = {"vth0": 0.4, "tox": 2.5e-9}

        writer.write_from_ir([model])

        # Verify file created
        assert output_file.exists()

        # Read content
        content = output_file.read_text()

        # Verify header
        assert "// Generated by SPICE Translator" in content

        # Verify model
        assert "model nch bsim4 {" in content
        assert "vth0 = 0.4" in content
        assert "tox = 2.5" in content

    def test_write_model_with_corners(self, tmp_path: Path) -> None:
        """Test writing model with corner variations."""
        output_file = tmp_path / "corners.scs"
        writer = SpectreWriter(output_file)

        # Create model with corners
        model = ModelIR(
            name="nch",
            model_type="bsim4",
            device_type=DeviceType.NMOS,
        )
        model.base_parameters = {"version": "4.7"}

        # Add TT corner
        tt_cond = Condition(corner=Corner.TT, temperature=Temperature.NOMINAL)
        model.add_variation(tt_cond, {"vth0": 0.4, "tox": 2.5e-9})

        # Add FF corner
        ff_cond = Condition(corner=Corner.FF, temperature=Temperature.NOMINAL)
        model.add_variation(ff_cond, {"vth0": 0.35, "tox": 2.4e-9})

        writer.write_from_ir([model])

        # Read content
        content = output_file.read_text()

        # Verify TT section
        assert "section tt {" in content
        assert "vth0 = 0.4" in content

        # Verify FF section
        assert "section ff {" in content
        assert "vth0 = 0.35" in content

