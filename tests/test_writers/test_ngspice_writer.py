    def test_device_type_mapping(self, tmp_path: Path) -> None:
        """Test device type to ngspice type mapping."""
        output_file = tmp_path / "types.lib"
        writer = NgspiceWriter(output_file)

        # Test various device types
        devices = [
            (DeviceType.NMOS, "nmos"),
            (DeviceType.PMOS, "pmos"),
            (DeviceType.NPN, "npn"),
            (DeviceType.PNP, "pnp"),
        ]

        models = []
        for i, (dev_type, expected_type) in enumerate(devices):
            model = ModelIR(
                name=f"dev{i}",
                model_type="bsim4",
                device_type=dev_type,
            )
            model.base_parameters = {"test": 1}
            models.append(model)

        writer.write_from_ir(models)

        content = output_file.read_text()

        # Verify correct type mapping
        for dev_type, expected_type in devices:
            assert f" {expected_type} " in content

