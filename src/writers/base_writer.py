"""
Abstract base writer for SPICE formats.

All format-specific writers inherit from this class and implement
write_from_ir() to convert IR to their target format.

Compliance: CONSTRAINTS.md
"""

from abc import ABC, abstractmethod
from typing import List
from pathlib import Path
import logging

from ..ir.model_ir import ModelIR

logger = logging.getLogger(__name__)


class BaseWriter(ABC):
    """
    Abstract base class for all SPICE format writers.
    
    Writers convert universal IR representation to format-specific output.
    Each format (Spectre, HSPICE, ngspice) has its own writer implementation.
    """
    
    def __init__(self, output_path: Path) -> None:
        """
        Initialize writer with output file path.
        
        Args:
            output_path: Path for output file
        """
        self.output_path = output_path
        logger.info(f"Initialized {self.get_format_name()} writer for {output_path}")
    
    @abstractmethod
    def get_format_name(self) -> str:
        """
        Get the format name this writer produces.
        
        Returns:
            Format name ('spectre', 'hspice', 'ngspice')
        """
        pass
    
    @abstractmethod
    def write_from_ir(self, models: List[ModelIR]) -> None:
        """
        Write IR models to output file in target format.
        
        This is the main method that subclasses must implement.
        
        Args:
            models: List of ModelIR objects to write
            
        Raises:
            ValueError: If models are invalid
            IOError: If file cannot be written
        """
        pass
    
    def _write_content(self, content: str) -> None:
        """
        Write content to output file with error handling.
        
        Args:
            content: Content to write
            
        Raises:
            IOError: If write fails
        """
        try:
            # Create parent directories if needed
            self.output_path.parent.mkdir(parents=True, exist_ok=True)
            
            # Write content
            self.output_path.write_text(content, encoding='utf-8')
            
            logger.info(f"Wrote {len(content)} characters to {self.output_path}")
        except Exception as e:
            logger.error(f"Failed to write file {self.output_path}: {e}")
            raise IOError(f"Write failed: {e}") from e
    
    def _generate_header(self, comment_char: str = "*") -> str:
        """
        Generate standard file header.
        
        Args:
            comment_char: Comment character for this format
            
        Returns:
            Header string
        """
        from datetime import datetime
        
        lines = [
            f"{comment_char} Generated by SPICE Translator IR-Based Framework",
            f"{comment_char} Target Format: {self.get_format_name()}",
            f"{comment_char} Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            f"{comment_char}",
        ]
        return '\n'.join(lines)
    
    def validate_models(self, models: List[ModelIR]) -> bool:
        """
        Validate models before writing.
        
        Args:
            models: Models to validate
            
        Returns:
            True if all models are valid
        """
        if not models:
            logger.warning("No models to write")
            return False
        
        for model in models:
            if not model.name:
                logger.error(f"Model has no name: {model}")
                return False
            if not model.model_type:
                logger.error(f"Model {model.name} has no type")
                return False
        
        return True
    
    def __repr__(self) -> str:
        """Developer-friendly representation."""
        return f"{self.__class__.__name__}(output='{self.output_path.name}')"
